#!/usr/bin/env python3
"""Writes crates/sake/src/d3d11_methods.rs (sake's vtables: each method's argument count) and
crates/kura/src/d3d11/names.rs (method names for traces) from mingw-w64's d3d10/d3d11/dxgi
headers, interface numbers 64+ as crates/kura/src/d3d11/mod.rs has them.

usage: gen-d3d11-methods.py [MINGW_INCLUDE]"""
import os, re, sys

IFACES = [  # (number, interface whose vtable is used)
    (64, 'IDXGIFactory2'), (65, 'IDXGIAdapter1'), (66, 'IDXGIOutput'), (67, 'IDXGISwapChain1'),
    (68, 'IDXGIDevice3'), (69, 'IDXGISurface1'), (70, 'ID3D11Device5'), (71, 'ID3D11DeviceContext4'),
    (72, 'ID3D11Buffer'), (73, 'ID3D11Texture1D'), (74, 'ID3D11Texture2D'), (75, 'ID3D11Texture3D'),
    (76, 'ID3D11ShaderResourceView'), (77, 'ID3D11RenderTargetView'), (78, 'ID3D11DepthStencilView'),
    (79, 'ID3D11UnorderedAccessView'), (80, 'ID3D11VertexShader'), (81, 'ID3D11PixelShader'),
    (82, 'ID3D11GeometryShader'), (83, 'ID3D11HullShader'), (84, 'ID3D11DomainShader'),
    (85, 'ID3D11ComputeShader'), (86, 'ID3D11InputLayout'), (87, 'ID3D11SamplerState'),
    (88, 'ID3D11BlendState1'), (89, 'ID3D11DepthStencilState'), (90, 'ID3D11RasterizerState2'),
    (91, 'ID3D11Query'), (92, 'ID3D11ClassLinkage'), (93, 'ID3D11CommandList'),
    (94, 'ID3D10Multithread'),
    # Direct3D 10 / 10.1 (crates/kura/src/d3d11/d3d10.rs): faces of the same objects
    (95, 'ID3D10Device1'), (96, 'ID3D10Buffer'), (97, 'ID3D10Texture1D'), (98, 'ID3D10Texture2D'),
    (99, 'ID3D10Texture3D'), (100, 'ID3D10ShaderResourceView1'), (101, 'ID3D10RenderTargetView'),
    (102, 'ID3D10DepthStencilView'), (103, 'ID3D10VertexShader'), (104, 'ID3D10GeometryShader'),
    (105, 'ID3D10PixelShader'), (106, 'ID3D10InputLayout'), (107, 'ID3D10SamplerState'),
    (108, 'ID3D10BlendState1'), (109, 'ID3D10DepthStencilState'), (110, 'ID3D10RasterizerState'),
    (111, 'ID3D10Query'),
    (112, 'IDXGIResource'), (113, 'ID3DUserDefinedAnnotation'),
]
# methods returning a float (x87): their own stub returns 0.0
FLOAT = {('ID3D11DeviceContext4', 'GetResourceMinLOD')}

inc = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/mingw-w64/include'
here = os.path.dirname(os.path.abspath(__file__))
src = ''.join(open(f'{inc}/{f}').read() for f in ['d3d10.h', 'd3d10_1.h', 'dxgi.h', 'dxgi1_2.h', 'dxgi1_3.h', 'd3d11.h', 'd3d11_1.h', 'd3d11_2.h', 'd3d11_3.h', 'd3d11_4.h'])
vt = {}
for m in re.finditer(r'typedef struct (\w+)Vtbl \{\s*BEGIN_INTERFACE(.*?)END_INTERFACE', src, re.S):
    name, body = m.groups()
    meths = []
    for mm in re.finditer(r'(\w[\w\s\*]*?)\s*\(\s*STDMETHODCALLTYPE\s*\*\s*(\w+)\s*\)\s*\((.*?)\);', body, re.S):
        params = [p for p in mm.group(3).split(',') if p.strip()]
        odd = [p for p in params if re.search(r'\b(INT64|LARGE_INTEGER|double|LUID)\b', p) and '*' not in p]
        wide = [p for p in params if re.search(r'\bUINT64\b', p) and '*' not in p]  # two dwords
        meths.append((mm.group(2), -1 if odd else len(params) + len(wide)))
    vt[name] = meths

for num, name in IFACES:
    for n, a in vt[name]:
        if a < 0:
            sys.exit(f'{name}::{n} has an argument that is not one dword')
# the method names for the host's traces
rs = ['// generated by host/gen-d3d11-methods.py: do not edit', '', '/// (interface name, method names) by interface number - 64',
      'pub const NAMES: &[(&str, &[&str])] = &[']
for num, name in IFACES:
    rs.append(f'    ("{name}", &[' + ', '.join(f'"{n}"' for n, _ in vt[name]) + ']),')
rs.append('];')
rs += ['', '/// Each method\'s argument count (dwords, `this` included) by interface number - 64', 'pub const ARGS: &[&[u8]] = &[']
for num, name in IFACES:
    rs.append('    &[' + ', '.join('2' if (name, n) in FLOAT else str(a) for n, a in vt[name]) + '],')
rs.append('];')
open(f'{here}/../crates/kura/src/d3d11/names.rs', 'w').write('\n'.join(rs) + '\n')
# sake's vtables (crates/sake/src/d3d11.rs): argument counts, 0 for the float methods
vn = ['//! generated by host/gen-d3d11-methods.py: do not edit. Per interface 64.., each method\'s',
      '//! argument count (dwords) with `this`; 0 marks a FLOAT method (returns 0.0 in ST0, 2 args).', '',
      f'pub const METHODS: [&[u8]; {len(IFACES)}] = [']
for num, name in IFACES:
    vn.append('    &[' + ', '.join('0' if (name, n) in FLOAT else str(a) for n, a in vt[name]) + '],')
vn.append('];')
open(f'{here}/../crates/sake/src/d3d11_methods.rs', 'w').write('\n'.join(vn) + '\n')
