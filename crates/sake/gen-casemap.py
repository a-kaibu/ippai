#!/usr/bin/env python3
"""Writes src/casemap_table.rs, Windows' case tables (CharUpperBuffW / CharLowerBuffW /
LCMapStringW LCMAP_UPPERCASE / LCMAP_LOWERCASE agree on every BMP code point) from the winref
casemap golden: python3 gen-casemap.py (run from crates/sake)."""
import os

here = os.path.dirname(os.path.abspath(__file__))
golden = os.path.join(here, "../../tests/winref/golden/casemap-32/stdout.txt")
up, lo = {}, {}
for line in open(golden):
    f = line.split()
    if len(f) != 10:
        continue
    c, u, l = int(f[0], 16), int(f[2], 16), int(f[4], 16)
    assert (u, l) == (int(f[7], 16), int(f[9], 16)), line
    if u != c:
        up[c] = u
    if l != c:
        lo[c] = l


def runs(m):
    """(first, last, step, delta): first, first+step, ... last map to c + delta"""
    out = []
    for c in sorted(m):
        d = m[c] - c
        if out:
            a, b, s, dd = out[-1]
            if dd == d and (a == b and c - b in (1, 2) or c - b == s):
                out[-1] = (a, c, c - b, d)
                continue
        out.append((c, c, 1, d))
    return out


def table(name, m):
    rows = runs(m)
    body = "".join(f"    (0x{a:04x}, 0x{b:04x}, {s}, {d}),\n" for a, b, s, d in rows)
    return f"pub(crate) static {name}: [(u16, u16, u8, i32); {len(rows)}] = [\n{body}];\n"


with open(os.path.join(here, "src/casemap_table.rs"), "w") as o:
    o.write("// Generated by gen-casemap.py from tests/winref/golden/casemap-32 (Windows Server 2025):\n")
    o.write("// (first, last, step, delta) runs, sorted: first, first+step, ..., last map to c + delta.\n\n")
    o.write(table("UPPER", up))
    o.write("\n")
    o.write(table("LOWER", lo))
