#!/bin/sh
# Builds crt.c into flat x86 code at AT for sake (src/guest_crt.bin + src/guest_crt.rs), and
# into x86-64 code (Microsoft's calling convention) at AT64 (src/guest_crt64.bin + .rs).
# Needs gcc with -m32 (freestanding: no 32-bit libc) and binutils.
set -e
cd "$(dirname "$0")"
OUT=../src
build() { # <-m32|-m64> <address> <ld emulation> <name> <extra flags>
  gcc $1 -O2 -ffreestanding -fno-builtin -fno-tree-loop-distribute-patterns -fno-pic -fno-pie \
    -fno-stack-protector -fno-asynchronous-unwind-tables -fno-jump-tables -mno-sse -mno-mmx -mno-80387 \
    -fcf-protection=none $5 -c crt.c -o /tmp/sake-guest-$4.o
  cat > /tmp/sake-guest-$4.ld <<LD
SECTIONS { . = $2; .all : { *(.text*) *(.rodata*) *(.data*) *(.bss*) *(COMMON) } /DISCARD/ : { *(*) } }
LD
  ld -m $3 -T /tmp/sake-guest-$4.ld -o /tmp/sake-guest-$4.elf /tmp/sake-guest-$4.o
  objcopy -O binary -j .all /tmp/sake-guest-$4.elf $OUT/$4.bin
  {
    echo "// generated by guest/gen-guest.sh from guest/crt.c: do not edit"
    echo "pub const AT: u32 = $2;"
    echo "pub const CODE: &[u8] = include_bytes!(\"$4.bin\");"
    echo "/// exported functions and the host slots, by address"
    echo "pub const SYMS: &[(&str, u32)] = &["
    nm /tmp/sake-guest-$4.elf | awk '$2 ~ /^[TBDC]$/ { printf "    (\"%s\", 0x%s),\n", $3, substr($1, length($1) - 7) }'
    echo "];"
  } > $OUT/$4.rs
  ls -l $OUT/$4.bin
}
build -m32 0x7fef0000 elf_i386 guest_crt ""
build -m64 0x7fef0000 elf_x86_64 guest_crt64 "-mabi=ms -mno-red-zone -mcmodel=small"
