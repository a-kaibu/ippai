#!/bin/sh
# Builds crt.c into flat x86 code at GUEST_AT for sake (src/guest_crt.bin + src/guest_crt.rs).
# Needs gcc with -m32 (freestanding: no 32-bit libc) and binutils.
set -e
cd "$(dirname "$0")"
AT=0x7fef0000
OUT=../src
gcc -m32 -O2 -ffreestanding -fno-builtin -fno-tree-loop-distribute-patterns -fno-pic -fno-pie \
  -fno-stack-protector -fno-asynchronous-unwind-tables -fno-jump-tables -mno-sse -mno-mmx -mno-80387 \
  -fcf-protection=none -c crt.c -o /tmp/sake-guest-crt.o
cat > /tmp/sake-guest.ld <<LD
SECTIONS { . = $AT; .all : { *(.text*) *(.rodata*) *(.data*) *(.bss*) *(COMMON) } /DISCARD/ : { *(*) } }
LD
ld -m elf_i386 -T /tmp/sake-guest.ld -o /tmp/sake-guest.elf /tmp/sake-guest-crt.o
objcopy -O binary -j .all /tmp/sake-guest.elf $OUT/guest_crt.bin
{
  echo "// generated by guest/gen-guest.sh from guest/crt.c: do not edit"
  echo "pub const AT: u32 = $AT;"
  echo "pub const CODE: &[u8] = include_bytes!(\"guest_crt.bin\");"
  echo "/// exported functions and the host slots, by address"
  echo "pub const SYMS: &[(&str, u32)] = &["
  nm /tmp/sake-guest.elf | awk '$2 ~ /^[TBDC]$/ { printf "    (\"%s\", 0x%s),\n", $3, $1 }'
  echo "];"
} > $OUT/guest_crt.rs
ls -l $OUT/guest_crt.bin
