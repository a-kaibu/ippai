#!/usr/bin/env python3
"""Writes the codec tables (src/*_tables.rs) from FFmpeg's sources: the VLC codes, levels,
bands and codebooks of its WMA / MS-MPEG4 / WMV / VC-1 decoders, which crates/wmcodec ports.

  gen_tables.py FFMPEG_SRC   (an FFmpeg 7.1 tree: https://ffmpeg.org/releases/ffmpeg-7.1.tar.xz)
"""
import re, sys, os

SRC = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))

C_TYPES = {'uint8_t': 'u8', 'int8_t': 'i8', 'uint16_t': 'u16', 'int16_t': 'i16', 'uint32_t': 'u32',
           'int32_t': 'i32', 'float': 'f32', 'int': 'i32', 'unsigned': 'u32', 'uint64_t': 'u64'}


def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)


def array(text, name):
    m = re.search(r'(?:static\s+)?(?:const\s+)?(\w+)\s+(?:const\s+)?' + re.escape(name) + r'((?:\s*\[[^\]]*\])+)\s*=\s*\{', text)
    if not m:
        raise SystemExit(f'no array {name}')
    ty = C_TYPES[m.group(1)]
    i = m.end()
    depth = 1
    while depth:
        c = text[i]
        depth += c == '{'
        depth -= c == '}'
        i += 1
    body = text[m.end():i - 1]
    dims = [d.strip() for d in re.findall(r'\[([^\]]*)\]', m.group(2))]
    num = r'-?(?:0x[0-9a-fA-F]+|\d+\.?\d*(?:e[-+]?\d+)?)[fFuUlL]*'
    sizes = [int(d, 0) if re.fullmatch(r'\d+|0x[0-9a-fA-F]+', d) else None for d in dims]
    if len(dims) >= 2 and '{' in body:
        # (nested braces: each level padded with zeros to its size, as C does)
        def level(txt, k):
            if k == len(dims) - 1:
                r = re.findall(num, txt)
                return r + ['0'] * ((sizes[k] or len(r)) - len(r))
            out, depth, start = [], 0, None
            for j, c in enumerate(txt):
                if c == '{':
                    if depth == 0:
                        start = j + 1
                    depth += 1
                elif c == '}':
                    depth -= 1
                    if depth == 0:
                        out.append(level(txt[start:j], k + 1))
            inner = 1
            for z in sizes[k + 1:]:
                inner *= z
            flat = [t for o in out for t in o]
            n = sizes[k] * inner if sizes[k] else len(flat)
            return flat + ['0'] * (n - len(flat))
        if len(dims) == 2:
            toks = []
            for row in re.findall(r'\{([^{}]*)\}', body):
                r = re.findall(num, row)
                n = sizes[-1] or len(r)
                toks += r + ['0'] * (n - len(r))
        else:
            toks = level(body, 0)
    else:
        toks = re.findall(num, body)
    vals = []
    for t in toks:
        # (a float's f, an integer's u / l; hex digits are not suffixes)
        t = t.rstrip('uUlL') if t.lower().lstrip('-').startswith('0x') else t.rstrip('fFuUlL')
        if ty == 'f32':
            vals.append(repr(float(t)) if not t.startswith('0x') else str(int(t, 16)))
        else:
            v = int(t, 0)
            # C wraps a negative initializer of an unsigned element (vc1 delta tables' -1 is 255)
            if v < 0 and ty[0] == 'u':
                v &= (1 << int(ty[1:])) - 1
            vals.append(str(v))
    return ty, vals


def emit(out, rust_name, ty, vals):
    out.append(f'pub static {rust_name}: [{ty}; {len(vals)}] = [')
    for k in range(0, len(vals), 16):
        out.append('    ' + ', '.join(v + ('_f32' if ty == 'f32' and '.' not in v and 'e' not in v else '') for v in vals[k:k + 16]) + ',')
    out.append('];')


def gen(path, items, header):
    out = ['//! Generated by gen_tables.py from FFmpeg 7.1 (LGPL-2.1-or-later): do not edit.', '#![allow(clippy::all)]', '']
    texts = {}
    for f, cname, rname in items:
        if f not in texts:
            texts[f] = strip_comments(open(os.path.join(SRC, f), encoding='utf-8', errors='replace').read())
        ty, vals = array(texts[f], cname)
        emit(out, rname, ty, vals)
        out.append('')
    open(os.path.join(HERE, 'src', path), 'w').write('\n'.join(out))


