#!/usr/bin/env python3
"""GL function signatures for sake's opengl32 (crates/sake/src/gl.rs) from vnhost's GL
(crates/vnhost/src/gl/*.rs): each function's wasm argument kinds, which say how to read its
stdcall arguments off the guest stack, and a caller per distinct signature.

  i: a 32-bit integer or pointer   b: GLboolean (u8)   f: f32   d: f64 (8 stack bytes)
  return: v (none), i, f, d (both in ST0)

Usage: [WINE_SRC=<wine source>] hangover/gen-sake-gl.py > crates/sake/src/gl_sigs.rs"""
import re, glob, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
funcs = {}
for path in sorted(glob.glob(f"{root}/crates/vnhost/src/gl/*.rs")):
    src = open(path).read()
    for m in re.finditer(r'extern "C" fn (gl\w+)\(([^)]*)\)\s*(?:->\s*([^{]+?))?\s*\{', src):
        name, args, ret = m.group(1), m.group(2).strip(), (m.group(3) or "").strip()
        kinds = ""
        for a in [a.strip() for a in args.split(",") if a.strip()]:
            ty = a.split(":", 1)[1].strip()
            kinds += {"f32": "f", "f64": "d", "u8": "b"}.get(ty, "i")
        r = {"": "v", "f32": "f", "f64": "d"}.get(ret, "i")
        funcs[name] = kinds + "_" + r

sigs = sorted(set(funcs.values()))
rty = {"v": "()", "i": "u32", "f": "f32", "d": "f64"}
aty = {"i": "u32", "b": "u32", "f": "f32", "d": "f64"}
out = ["// generated by hangover/gen-sake-gl.py from crates/vnhost/src/gl; do not edit",
       "#![allow(clippy::all)]",
       "",
       "/// (name, signature index)",
       "pub const FUNCS: &[(&str, u16)] = &["]
for name in sorted(funcs):
    out.append(f'    ("{name}", {sigs.index(funcs[name])}),')
out.append("];")
out.append("")
out.append("/// each signature's argument kinds and return kind")
out.append("pub const SIGS: &[(&str, char)] = &[")
for s in sigs:
    a, r = s.split("_")
    out.append(f'    ("{a}", \'{r}\'),')
out.append("];")
out.append("")
out.append("pub enum Ret { V, I(u32), F(f64) }")
out.append("")
out.append("/// Calls `f` (signature `sig`) with the arguments already split into words (a d: two).")
out.append("pub unsafe fn call(sig: u16, f: *const (), w: &[u32]) -> Ret {")
out.append("    match sig {")
for k, s in enumerate(sigs):
    a, r = s.split("_")
    params = ", ".join(aty[x] for x in a)
    vals, i = [], 0
    for x in a:
        if x == "i":
            vals.append(f"w[{i}]"); i += 1
        elif x == "b":
            vals.append(f"w[{i}] & 0xff"); i += 1
        elif x == "f":
            vals.append(f"f32::from_bits(w[{i}])"); i += 1
        else:
            vals.append(f"f64::from_bits(w[{i}] as u64 | (w[{i + 1}] as u64) << 32)"); i += 2
    call = f"std::mem::transmute::<*const (), extern \"C\" fn({params}) -> {rty[r]}>(f)({', '.join(vals)})"
    wrap = {"v": f"{{ {call}; Ret::V }}", "i": f"Ret::I({call})", "f": f"Ret::F({call} as f64)", "d": f"Ret::F({call})"}[r]
    out.append(f"        {k} => {wrap},")
out.append("        _ => Ret::V,")
out.append("    }")
out.append("}")
# every other GL function (Wine's include/wine/wgl.h): a do-nothing one, as winebrowser.drv
# has (stack bytes to pop)
wgl = os.environ.get("WINE_SRC", "/home/user/work/wine-src") + "/include/wine/wgl.h"
stubs = {}
for m in re.finditer(r"typedef\s+.+?\s*\(GLAPIENTRY \*PFN_(gl\w+)\)\(\s*(.*?)\s*\);", open(wgl).read()):
    name, args = m.group(1), m.group(2).strip()
    if name in funcs:
        continue
    n = 0
    for a in [a.strip() for a in args.split(",") if a.strip() and a.strip() != "void"]:
        wide = "*" not in a and re.search(r"\b(GLdouble|GLclampd|GLint64|GLuint64|GLint64EXT|GLuint64EXT)\b", a)
        n += 8 if wide else 4
    stubs[name] = n
out.append("")
out.append("/// GL functions vnhost does not have, and their stack bytes (do-nothing)")
out.append("pub const STUBS: &[(&str, u8)] = &[")
for name in sorted(stubs):
    out.append(f'    ("{name}", {stubs[name]}),')
out.append("];")
print("\n".join(out))
