#!/usr/bin/env python3
"""Do-nothing GL functions for winebrowser.drv's WGL driver (dlls/winebrowser.drv/glstubs.h):
win32u and opengl32 call every GL function through pointers whose wasm signatures must match,
so the ones vnhost does not have (crates/vnhost/src/gl) get a stub of the right type.
Usage: gen-gl-stubs.py <wine source>"""
import re, sys

src = sys.argv[1]
text = open(f"{src}/include/wine/wgl.h").read()
funcs = []
for m in re.finditer(r"typedef\s+(.+?)\s*\(GLAPIENTRY \*PFN_(gl\w+)\)\(\s*(.*?)\s*\);", text):
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
    funcs.append((name, ret, args))
funcs = sorted(set(funcs))
out = ["/* generated by hangover/gen-gl-stubs.py from include/wine/wgl.h */"]
for name, ret, args in funcs:
    body = "" if ret == "void" else f" return ({ret})0;"
    out.append(f"static {ret} GLAPIENTRY stub_{name}( {args or 'void'} ) {{{body} }}")
out.append("static const struct gl_stub { const char *name; void *func; } gl_stubs[] =\n{")
for name, _, _ in funcs:
    out.append(f'    {{ "{name}", (void *)stub_{name} }},')
out.append("};")
open(f"{src}/dlls/winebrowser.drv/glstubs.h", "w").write("\n".join(out) + "\n")
print(len(funcs), "stubs")
